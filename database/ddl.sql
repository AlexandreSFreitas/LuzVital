-- REGIAO: bairro ou área usada para cruzar a interrupção com os pacientes
CREATE TABLE regiao (
    id_regiao  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR2(80) NOT NULL,
    cidade     VARCHAR2(80) NOT NULL,
    uf         CHAR(2)      NOT NULL,
    CONSTRAINT pk_regiao             PRIMARY KEY (id_regiao),
    CONSTRAINT uq_regiao_nome_cidade UNIQUE (nome, cidade),
    CONSTRAINT ck_regiao_uf          CHECK (uf = UPPER(uf))
);

-- PACIENTE: paciente eletrodependente (somente dados fictícios), com endereço
CREATE TABLE paciente (
    id_paciente            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome                   VARCHAR2(120) NOT NULL,
    data_nascimento        DATE          NOT NULL,
    logradouro             VARCHAR2(120) NOT NULL,
    numero                 VARCHAR2(10)  NOT NULL,
    complemento            VARCHAR2(60),
    cep                    CHAR(8)       NOT NULL,
    id_regiao              NUMBER        NOT NULL,
    observacao_atendimento VARCHAR2(255),
    ativo                  CHAR(1)       DEFAULT 'S' NOT NULL,
    data_cadastro          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_paciente       PRIMARY KEY (id_paciente),
    CONSTRAINT ck_paciente_cep   CHECK (REGEXP_LIKE(cep, '^[0-9]{8}$')),
    CONSTRAINT ck_paciente_ativo CHECK (ativo IN ('S', 'N'))
);

-- EQUIPAMENTO: catálogo de tipos de equipamento médico e seu consumo
CREATE TABLE equipamento (
    id_equipamento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome           VARCHAR2(80) NOT NULL,
    categoria      VARCHAR2(30) NOT NULL,
    consumo_watts  NUMBER(6)    NOT NULL,
    suporte_vida   CHAR(1)      DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_equipamento              PRIMARY KEY (id_equipamento),
    CONSTRAINT uq_equipamento_nome         UNIQUE (nome),
    CONSTRAINT ck_equipamento_categoria    CHECK (categoria IN ('RESPIRATORIO', 'ALIMENTACAO', 'MONITORAMENTO', 'OUTRO')),
    CONSTRAINT ck_equipamento_consumo      CHECK (consumo_watts > 0),
    CONSTRAINT ck_equipamento_suporte_vida CHECK (suporte_vida IN ('S', 'N'))
);

-- PACIENTE_EQUIPAMENTO: unidade de equipamento que o paciente usa, com a autonomia da bateria
CREATE TABLE paciente_equipamento (
    id_paciente_equipamento NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_paciente             NUMBER    NOT NULL,
    id_equipamento          NUMBER    NOT NULL,
    autonomia_bateria_min   NUMBER(5) DEFAULT 0 NOT NULL,
    fonte_alternativa       VARCHAR2(60),
    CONSTRAINT pk_paciente_equipamento PRIMARY KEY (id_paciente_equipamento),
    CONSTRAINT ck_pac_equip_autonomia  CHECK (autonomia_bateria_min >= 0)
);

-- CONTATO: familiar, cuidador ou equipe de saúde
CREATE TABLE contato (
    id_contato NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nome       VARCHAR2(120) NOT NULL,
    tipo       VARCHAR2(20)  NOT NULL,
    telefone   VARCHAR2(20)  NOT NULL,
    email      VARCHAR2(120),
    CONSTRAINT pk_contato      PRIMARY KEY (id_contato),
    CONSTRAINT ck_contato_tipo CHECK (tipo IN ('FAMILIAR', 'CUIDADOR', 'EQUIPE_SAUDE'))
);

-- PACIENTE_CONTATO: rede de apoio do paciente, com a ordem de acionamento
CREATE TABLE paciente_contato (
    id_paciente       NUMBER    NOT NULL,
    id_contato        NUMBER    NOT NULL,
    ordem_acionamento NUMBER(2) NOT NULL,
    vinculo           VARCHAR2(40),
    CONSTRAINT pk_paciente_contato    PRIMARY KEY (id_paciente, id_contato),
    CONSTRAINT uq_pac_contato_ordem   UNIQUE (id_paciente, ordem_acionamento),
    CONSTRAINT ck_pac_contato_ordem   CHECK (ordem_acionamento >= 1)
);

-- INTERRUPCAO: falta de energia numa região (no MVP, simulada)
CREATE TABLE interrupcao (
    id_interrupcao       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_regiao            NUMBER       NOT NULL,
    data_inicio          TIMESTAMP    NOT NULL,
    data_fim             TIMESTAMP,
    duracao_estimada_min NUMBER(5),
    origem               VARCHAR2(20) NOT NULL,
    status               VARCHAR2(15) DEFAULT 'ABERTA' NOT NULL,
    CONSTRAINT pk_interrupcao          PRIMARY KEY (id_interrupcao),
    CONSTRAINT ck_interrupcao_periodo  CHECK (data_fim IS NULL OR data_fim >= data_inicio),
    CONSTRAINT ck_interrupcao_duracao  CHECK (duracao_estimada_min IS NULL OR duracao_estimada_min > 0),
    CONSTRAINT ck_interrupcao_origem   CHECK (origem IN ('SIMULADA', 'MANUAL', 'DISPOSITIVO')),
    CONSTRAINT ck_interrupcao_status   CHECK (status IN ('ABERTA', 'ENCERRADA')),
    -- aberta não tem fim; encerrada precisa ter fim
    CONSTRAINT ck_interrupcao_fim      CHECK ((status = 'ABERTA' AND data_fim IS NULL)
                                           OR (status = 'ENCERRADA' AND data_fim IS NOT NULL))
);

-- ALERTA: aviso para um contato de um paciente afetado, com a confirmação
CREATE TABLE alerta (
    id_alerta        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_interrupcao   NUMBER       NOT NULL,
    id_paciente      NUMBER       NOT NULL,
    id_contato       NUMBER       NOT NULL,
    prioridade       NUMBER(1)    NOT NULL,
    status           VARCHAR2(15) DEFAULT 'PENDENTE' NOT NULL,
    data_criacao     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    data_confirmacao TIMESTAMP,
    CONSTRAINT pk_alerta              PRIMARY KEY (id_alerta),
    CONSTRAINT uq_alerta              UNIQUE (id_interrupcao, id_paciente, id_contato),
    CONSTRAINT ck_alerta_prioridade   CHECK (prioridade BETWEEN 1 AND 3),
    CONSTRAINT ck_alerta_status       CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'SEM_RESPOSTA')),
    -- confirmado exige data de confirmação
    CONSTRAINT ck_alerta_confirmacao  CHECK (status <> 'CONFIRMADO' OR data_confirmacao IS NOT NULL)
);

-- ACAO_APOIO: o que foi feito depois do alerta
CREATE TABLE acao_apoio (
    id_acao       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_alerta     NUMBER        NOT NULL,
    tipo          VARCHAR2(30)  NOT NULL,
    descricao     VARCHAR2(255) NOT NULL,
    data_registro TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_acao_apoio      PRIMARY KEY (id_acao),
    CONSTRAINT ck_acao_apoio_tipo CHECK (tipo IN ('CONTATO_REALIZADO', 'DESLOCAMENTO', 'ENERGIA_RESTABELECIDA',
                                                  'ORIENTADO_SAMU_192', 'OUTRO'))
);

-- =====================================================================
-- 2. ALTER TABLE: chaves estrangeiras (relacionamentos)
-- =====================================================================

-- REGIAO 1:N PACIENTE
ALTER TABLE paciente
    ADD CONSTRAINT fk_paciente_regiao
    FOREIGN KEY (id_regiao) REFERENCES regiao (id_regiao);

-- PACIENTE 1:N PACIENTE_EQUIPAMENTO (removido junto com o paciente)
ALTER TABLE paciente_equipamento
    ADD CONSTRAINT fk_pac_equip_paciente
    FOREIGN KEY (id_paciente) REFERENCES paciente (id_paciente) ON DELETE CASCADE;

-- EQUIPAMENTO 1:N PACIENTE_EQUIPAMENTO
ALTER TABLE paciente_equipamento
    ADD CONSTRAINT fk_pac_equip_equipamento
    FOREIGN KEY (id_equipamento) REFERENCES equipamento (id_equipamento);

-- PACIENTE 1:N PACIENTE_CONTATO
ALTER TABLE paciente_contato
    ADD CONSTRAINT fk_pac_contato_paciente
    FOREIGN KEY (id_paciente) REFERENCES paciente (id_paciente);

-- CONTATO 1:N PACIENTE_CONTATO
ALTER TABLE paciente_contato
    ADD CONSTRAINT fk_pac_contato_contato
    FOREIGN KEY (id_contato) REFERENCES contato (id_contato);

-- REGIAO 1:N INTERRUPCAO
ALTER TABLE interrupcao
    ADD CONSTRAINT fk_interrupcao_regiao
    FOREIGN KEY (id_regiao) REFERENCES regiao (id_regiao);

-- INTERRUPCAO 1:N ALERTA
ALTER TABLE alerta
    ADD CONSTRAINT fk_alerta_interrupcao
    FOREIGN KEY (id_interrupcao) REFERENCES interrupcao (id_interrupcao);

-- PACIENTE_CONTATO 1:N ALERTA (FK composta: o alerta vai para um contato daquele paciente)
ALTER TABLE alerta
    ADD CONSTRAINT fk_alerta_pac_contato
    FOREIGN KEY (id_paciente, id_contato) REFERENCES paciente_contato (id_paciente, id_contato);

-- ALERTA 1:N ACAO_APOIO
ALTER TABLE acao_apoio
    ADD CONSTRAINT fk_acao_apoio_alerta
    FOREIGN KEY (id_alerta) REFERENCES alerta (id_alerta);

